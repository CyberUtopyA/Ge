// src/modeler/registry.ts
import type { EnergyAssetDescriptor, AssetVerb } from "../utopy/types.simbiosis";

type AssetMap = Map<string, EnergyAssetDescriptor>;

const REGISTRY: AssetMap = new Map();

/** añade/actualiza un descriptor (key por kind para lookup rápido) */
export function upsertAsset(desc: EnergyAssetDescriptor) {
  REGISTRY.set(desc.kind, { ...desc });
}

/** añade varios */
export function upsertAssets(list: EnergyAssetDescriptor[] = []) {
  for (const d of list) upsertAsset(d);
}

/** obtiene uno o null (por kind) */
export function getAsset(kind: string): EnergyAssetDescriptor | null {
  return REGISTRY.get(kind) || null;
}

/** lista todo para paleta/sugerencias */
export function listAssets(): EnergyAssetDescriptor[] {
  return Array.from(REGISTRY.values());
}

/** fallback por si no hay descriptor conocido en el registro */
export function fallbackAsset(kind: string): EnergyAssetDescriptor {
  const baseName = kind.split(".").slice(-1)[0] || kind;
  const label = baseName.charAt(0).toUpperCase() + baseName.slice(1);

  const verbs: AssetVerb[] = [
    { say: "asset.create", sym: "⚡" }, // ← objeto, no string
  ];

  return {
    id: kind,                // ← obligatorio en EnergyAssetDescriptor
    kind,
    label,
    icon: "⚙️",
    verbs,
    display: {
      name: label,           // ← obligatorio en display
      icon: "⚙️",
      color: "#9bb7d3",
    },
    // meta opcional si quieres
    meta: { autogenerated: true },
  };
}
